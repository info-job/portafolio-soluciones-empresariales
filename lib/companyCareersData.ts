/**
 * Busca si una empresa cuenta con una página directa de "Trabaja con Nosotros" registrada.
 */
export const findCompanyCareerEntry = (companyName: string): CompanyCareerEntry | undefined => {
  if (!companyName) return undefined;
  const normalized = companyName.toLowerCase().trim();
  
  return COMPANY_CAREERS_DIRECTORY.find(entry => {
    if (entry.name.toLowerCase() === normalized) return true;
    return entry.aliases.some(alias => normalized.includes(alias) || alias.includes(normalized));
  });
};

/**
 * Resuelve la URL más directa y fidedigna para postular en la sección "Trabaja con Nosotros" de una empresa.
 * Si la empresa está en el directorio oficial, retorna su página institucional.
 * Si no está, genera un enlace de búsqueda directa de alta precisión en Google hacia su sección oficial.
 */
export const getCompanyTrabajaConNosotrosUrl = (companyName: string, jobTitle?: string): string => {
  const cleanCompany = (companyName || '').trim();
  const entry = findCompanyCareerEntry(cleanCompany);
  
  if (entry) {
    return entry.careerUrl;
  }
  
  // Búsqueda directa del portal de empleo oficial de la empresa
  const cleanTitle = (jobTitle || '').replace(/\(.*?\)/g, '').trim();
  const q = `"${cleanCompany}" "trabaja con nosotros" OR "careers" Chile ${cleanTitle}`.trim();
  return `https://www.google.com/search?q=${encodeURIComponent(q)}`;
};

